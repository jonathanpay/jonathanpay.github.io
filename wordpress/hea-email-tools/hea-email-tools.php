const HEA_ET_VERSION = '1.0.0';
const HEA_ET_OPTION  = 'hea_et_settings';

/*
 * Everything under assets/ and templates/, and tools.json, is generated by
 * wordpress/build-email-tools.mjs from the tool pages in email-tools/.
 * Only this file and uninstall.php are written by hand.
 */

/** The build manifest: page titles, scripts and styles for each tool, and file hashes. */
function hea_et_manifest() {
	static $manifest = null;
	if ( null === $manifest ) {
		$json     = file_get_contents( plugin_dir_path( __FILE__ ) . 'tools.json' ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents
		$manifest = json_decode( (string) $json, true );
		if ( ! is_array( $manifest ) ) {
			$manifest = array( 'tools' => array(), 'scripts' => array(), 'styles' => array() );
		}
	}
	return $manifest;
}

/**
 * Saved settings, with defaults.
 *
 * base_path: where the tool pages live. The index is at the base path and
 *            each tool is a child page named after its key, so the default
 *            gives /email-tools/ and /email-tools/tone/.
 */
function hea_et_settings() {
	$saved = get_option( HEA_ET_OPTION, array() );
	return wp_parse_args(
		is_array( $saved ) ? $saved : array(),
		array( 'base_path' => '/email-tools/' )
	);
}

/** Every page address, keyed by tool ("index" is the tools index). */
function hea_et_page_urls() {
	$base = trailingslashit( '/' . trim( hea_et_settings()['base_path'], '/' ) );
	$urls = array();
	foreach ( array_keys( hea_et_manifest()['tools'] ) as $key ) {
		$urls[ $key ] = home_url( 'index' === $key ? $base : $base . $key . '/' );
	}
	return $urls;
}

// ---- Front end ----------------------------------------------------------------

function hea_et_asset_url( $path, $hash ) {
	return plugin_dir_url( __FILE__ ) . 'assets/' . $path . ( $hash ? '?v=' . $hash : '' );
}

/**
 * Loads one tool's styles and scripts. Scripts are ES modules loaded at the
 * exact URL other modules import them by, so a shared module only runs once.
 */
function hea_et_enqueue( $key ) {
	$m    = hea_et_manifest();
	$tool = $m['tools'][ $key ];

	wp_enqueue_style( 'hea-et', hea_et_asset_url( 'css/email-tools.css', $m['styles']['email-tools.css'] ?? '' ), array(), null );
	if ( ! empty( $tool['css'] ) ) {
		wp_enqueue_style( 'hea-et-' . $key, hea_et_asset_url( 'css/' . $tool['css'], $m['styles'][ $tool['css'] ] ?? '' ), array( 'hea-et' ), null );
	}

	// Where the other tools are, and that course links stay on this site.
	// Must run before the modules, which are deferred.
	static $configured = false;
	if ( ! $configured ) {
		$configured = true;
		wp_register_script( 'hea-et-config', false, array(), HEA_ET_VERSION, false );
		wp_enqueue_script( 'hea-et-config' );
		wp_add_inline_script(
			'hea-et-config',
			'window.HEA_ET_CONFIG=' . wp_json_encode(
				array(
					'internal' => true,
					'pages'    => array_map( 'wp_make_link_relative', hea_et_page_urls() ),
				)
			) . ';'
		);
	}

	foreach ( $tool['modules'] as $file ) {
		$id = 'hea-et/' . $file;
		wp_register_script_module( $id, hea_et_asset_url( 'js/' . $file, $m['scripts'][ $file ] ?? '' ), array(), null );
		wp_enqueue_script_module( $id );
	}
	if ( ! empty( $tool['classic'] ) ) {
		wp_enqueue_script( 'hea-et-' . $key . '-inline', hea_et_asset_url( 'js/' . $tool['classic'], $m['scripts'][ $tool['classic'] ] ?? '' ), array(), null, true );
	}
}

/** A tool's markup, with links to the other tools filled in. */
function hea_et_render( $key ) {
	$m = hea_et_manifest();
	if ( empty( $m['tools'][ $key ] ) ) {
		return current_user_can( 'edit_posts' )
			? '<p><strong>HEA Email Tools:</strong> there is no tool called "' . esc_html( $key ) . '". Settings → Email tools lists the names.</p>'
			: '';
	}

	$template = file_get_contents( plugin_dir_path( __FILE__ ) . 'templates/' . $key . '.html' ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents
	$template = preg_replace( '/^<!--.*?-->\s*/s', '', (string) $template );
	$urls     = hea_et_page_urls();
	$html     = preg_replace_callback(
		'/\{\{page:([a-z0-9-]+)\}\}/',
		function ( $match ) use ( $urls ) {
			return isset( $urls[ $match[1] ] ) ? esc_url( $urls[ $match[1] ] ) : '#';
		},
		$template
	);

	hea_et_enqueue( $key );

	$back = 'index' === $key || 'dmarc-checker' === $key
		? ''
		: '<p class="hea-et-back"><a href="' . esc_url( $urls['index'] ) . '">← All email tools</a></p>';

	$schema = '';
	foreach ( $m['tools'][ $key ]['ldjson'] as $json ) {
		$schema .= '<script type="application/ld+json">' . $json . '</script>';
	}

	return '<div id="hea-et" class="hea-et hea-et--' . esc_attr( $key ) . '">'
		. $back
		. $html
		. '<noscript><p>These tools need JavaScript. Please switch it on, or open this page in another browser.</p></noscript>'
		. '</div>'
		. $schema;
}

add_shortcode( 'hea_email_tools', 'hea_et_index_shortcode' );
function hea_et_index_shortcode() {
	return hea_et_render( 'index' );
}

add_shortcode( 'hea_email_tool', 'hea_et_tool_shortcode' );
function hea_et_tool_shortcode( $atts ) {
	$atts = shortcode_atts( array( 'name' => '' ), $atts, 'hea_email_tool' );
	return hea_et_render( sanitize_key( $atts['name'] ) );
}

// ---- Settings → Email tools ---------------------------------------------------

add_action( 'admin_menu', 'hea_et_admin_menu' );
function hea_et_admin_menu() {
	add_options_page( 'Email tools', 'Email tools', 'manage_options', 'hea-email-tools', 'hea_et_settings_page' );
}

add_filter( 'plugin_action_links_' . plugin_basename( __FILE__ ), 'hea_et_action_links' );
function hea_et_action_links( $links ) {
	array_unshift( $links, '<a href="' . esc_url( admin_url( 'options-general.php?page=hea-email-tools' ) ) . '">Settings</a>' );
	return $links;
}

add_action( 'admin_init', 'hea_et_admin_init' );
function hea_et_admin_init() {
	register_setting(
		'hea_et',
		HEA_ET_OPTION,
		array(
			'type'              => 'array',
			'sanitize_callback' => 'hea_et_sanitize',
			'default'           => array(),
		)
	);
}

function hea_et_sanitize( $input ) {
	$path = isset( $input['base_path'] ) ? (string) $input['base_path'] : '';
	$path = trim( preg_replace( '#[^a-z0-9/-]#', '', strtolower( $path ) ), '/' );
	return array( 'base_path' => $path ? '/' . $path . '/' : '/email-tools/' );
}

function hea_et_settings_page() {
	if ( ! current_user_can( 'manage_options' ) ) {
		return;
	}
	$s    = hea_et_settings();
	$m    = hea_et_manifest();
	$urls = hea_et_page_urls();
	?>
	<div class="wrap">
		<h1>Email tools</h1>
		<p>Each tool is a page with a Shortcode block. The tools link to each other at the addresses below, so the pages must be published at exactly these addresses: create the index page first, then each tool as a child page of it with the slug shown.</p>
		<form method="post" action="options.php">
			<?php settings_fields( 'hea_et' ); ?>
			<table class="form-table" role="presentation">
				<tr>
					<th scope="row"><label for="hea-et-base">Tools index address</label></th>
					<td>
						<input type="text" class="regular-text code" id="hea-et-base" name="<?php echo esc_attr( HEA_ET_OPTION ); ?>[base_path]" value="<?php echo esc_attr( $s['base_path'] ); ?>">
						<p class="description">The path of the index page. Default <code>/email-tools/</code>.</p>
					</td>
				</tr>
			</table>
			<?php submit_button(); ?>
		</form>

		<h2>Pages</h2>
		<table class="widefat striped" style="max-width:1100px">
			<thead><tr><th>Page title</th><th>Address</th><th>Shortcode</th><th>Status</th></tr></thead>
			<tbody>
			<?php foreach ( $m['tools'] as $key => $tool ) : ?>
				<?php
				$url       = $urls[ $key ];
				$post_id   = url_to_postid( $url );
				$published = $post_id && 'publish' === get_post_status( $post_id );
				$code      = 'index' === $key ? '[hea_email_tools]' : '[hea_email_tool name="' . $key . '"]';
				?>
				<tr>
					<td><?php echo esc_html( $tool['title'] ); ?></td>
					<td><a href="<?php echo esc_url( $url ); ?>"><?php echo esc_html( wp_make_link_relative( $url ) ); ?></a></td>
					<td><code><?php echo esc_html( $code ); ?></code></td>
					<td><?php echo $published ? '✓ Published' : '<strong>Not found</strong>'; ?></td>
				</tr>
			<?php endforeach; ?>
			</tbody>
		</table>
	</div>
	<?php
}
