#!/usr/bin/env node
// Builds the generated half of the HEA Email Tools WordPress plugin from the
// tool pages in email-tools/, which stay the single source.
//
//   node wordpress/build-email-tools.mjs            # writes wordpress/hea-email-tools/
//   node wordpress/build-email-tools.mjs --out DIR  # writes somewhere else (the tests use this)
//
// What it does, per page:
// - takes the content of <main>, drops the page's own <h1> (the WordPress page
//   title is the one H1) and turns other tool links into {{page:key}}
//   placeholders the plugin fills with the Academy page addresses;
// - keeps course and contact links on the site (/courses/…?ref=, /contact/);
// - scopes every stylesheet to #hea-et, so the theme and the tools can't
//   restyle each other;
// - copies the scripts, adding ?v=<hash> to their imports so browsers fetch
//   new files after an update;
// - writes templates/<key>.html and a tools.json manifest for the PHP.
//
// hea-email-tools.php and uninstall.php are written by hand and never touched.

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, writeFileSync, copyFileSync, rmSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { TOOL_FILES } from "../email-tools/assets/site.js";

const here = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(here, "../email-tools");
// The tool pages. Once jonathanpay.github.io/email-tools/ redirects to the
// Academy, the pages move to wordpress/email-tools-pages/ (not published);
// scripts and styles stay in email-tools/assets/.
const PAGES = existsSync(resolve(here, "email-tools-pages")) ? resolve(here, "email-tools-pages") : SRC;
const FONTS = resolve(here, "hea-maturity-assessment/assets/fonts");
const outArg = process.argv.indexOf("--out");
const OUT = outArg > -1 ? resolve(process.argv[outArg + 1]) : resolve(here, "hea-email-tools");
const SCOPE = "#hea-et";
const GENERATED = "Generated by wordpress/build-email-tools.mjs from email-tools/. Edit the source, then rebuild.";

const FILE_TO_KEY = Object.fromEntries(Object.entries(TOOL_FILES).map(([k, f]) => [f, k]));
const hash = (text) => createHash("sha256").update(text).digest("hex").slice(0, 10);

// ---- CSS scoping --------------------------------------------------------------

function splitSelectors(prelude) {
  const out = [];
  let depth = 0, cur = "";
  for (const ch of prelude) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) { out.push(cur); cur = ""; } else cur += ch;
  }
  out.push(cur);
  return out.map((s) => s.trim()).filter(Boolean);
}

export function scopeSelector(sel) {
  if (/^(html|body|:root)\b/.test(sel)) return sel.replace(/^(html|body|:root)/, SCOPE);
  if (/^\.hea(?![\w-])/.test(sel)) return sel.replace(/^\.hea/, SCOPE);
  return `${SCOPE} ${sel}`;
}

export function scopeCss(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, "");
  let out = "", i = 0;
  while (i < css.length) {
    const open = css.indexOf("{", i);
    if (open === -1) {
      if (css.slice(i).trim()) throw new Error(`Unparsed CSS: ${css.slice(i, i + 80)}`);
      break;
    }
    const prelude = css.slice(i, open).trim();
    if (/;/.test(prelude)) throw new Error(`CSS statement before a block isn't supported: ${prelude.slice(0, 80)}`);
    let depth = 1, j = open + 1;
    while (depth && j < css.length) {
      if (css[j] === "{") depth++;
      else if (css[j] === "}") depth--;
      j++;
    }
    const body = css.slice(open + 1, j - 1).trim();
    if (/^@(media|supports|container)/.test(prelude)) out += `${prelude}{${scopeCss(body)}}\n`;
    else if (prelude.startsWith("@")) out += `${prelude}{${body}}\n`;
    else out += `${splitSelectors(prelude).map(scopeSelector).join(",")}{${body}}\n`;
    i = j;
  }
  return out;
}

