#!/usr/bin/env node
// Builds the generated half of the HEA Email Tools WordPress plugin from the
// tool pages in email-tools/, which stay the single source.
//
//   node wordpress/build-email-tools.mjs            # writes wordpress/hea-email-tools/
//   node wordpress/build-email-tools.mjs --out DIR  # writes somewhere else (the tests use this)
//
// What it does, per page:
// - takes the content of <main>, drops the page's own <h1> (the WordPress page
//   title is the one H1) and turns other tool links into {{page:key}}
//   placeholders the plugin fills with the Academy page addresses;
// - keeps course and contact links on the site (/courses/…?ref=, /contact/);
// - scopes every stylesheet to #hea-et, so the theme and the tools can't
//   restyle each other;
// - copies the scripts, adding ?v=<hash> to their imports so browsers fetch
//   new files after an update;
// - writes templates/<key>.html and a tools.json manifest for the PHP.
//
// hea-email-tools.php and uninstall.php are written by hand and never touched.

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, writeFileSync, copyFileSync, rmSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { TOOL_FILES } from "../email-tools/assets/site.js";

const here = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(here, "../email-tools");
// The tool pages. Once jonathanpay.github.io/email-tools/ redirects to the
// Academy, the pages move to wordpress/email-tools-pages/ (not published);
// scripts and styles stay in email-tools/assets/.
const PAGES = existsSync(resolve(here, "email-tools-pages")) ? resolve(here, "email-tools-pages") : SRC;
const FONTS = resolve(here, "hea-maturity-assessment/assets/fonts");
const outArg = process.argv.indexOf("--out");
const OUT = outArg > -1 ? resolve(process.argv[outArg + 1]) : resolve(here, "hea-email-tools");
const SCOPE = "#hea-et";
const GENERATED = "Generated by wordpress/build-email-tools.mjs from email-tools/. Edit the source, then rebuild.";

const FILE_TO_KEY = Object.fromEntries(Object.entries(TOOL_FILES).map(([k, f]) => [f, k]));
const hash = (text) => createHash("sha256").update(text).digest("hex").slice(0, 10);

// ---- CSS scoping --------------------------------------------------------------

function splitSelectors(prelude) {
  const out = [];
  let depth = 0, cur = "";
  for (const ch of prelude) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) { out.push(cur); cur = ""; } else cur += ch;
  }
  out.push(cur);
  return out.map((s) => s.trim()).filter(Boolean);
}

export function scopeSelector(sel) {
  if (/^(html|body|:root)\b/.test(sel)) return sel.replace(/^(html|body|:root)/, SCOPE);
  if (/^\.hea(?![\w-])/.test(sel)) return sel.replace(/^\.hea/, SCOPE);
  return `${SCOPE} ${sel}`;
}

export function scopeCss(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, "");
  let out = "", i = 0;
  while (i < css.length) {
    const open = css.indexOf("{", i);
    if (open === -1) {
      if (css.slice(i).trim()) throw new Error(`Unparsed CSS: ${css.slice(i, i + 80)}`);
      break;
    }
    const prelude = css.slice(i, open).trim();
    if (/;/.test(prelude)) throw new Error(`CSS statement before a block isn't supported: ${prelude.slice(0, 80)}`);
    let depth = 1, j = open + 1;
    while (depth && j < css.length) {
      if (css[j] === "{") depth++;
      else if (css[j] === "}") depth--;
      j++;
    }
    const body = css.slice(open + 1, j - 1).trim();
    if (/^@(media|supports|container)/.test(prelude)) out += `${prelude}{${scopeCss(body)}}\n`;
    else if (prelude.startsWith("@")) out += `${prelude}{${body}}\n`;
    else out += `${splitSelectors(prelude).map(scopeSelector).join(",")}{${body}}\n`;
    i = j;
  }
  return out;
}

// Theme styles that would otherwise leak into the tools. Same idea as the
// maturity assessment's reset, at the same ID specificity.
const RESET = `
${SCOPE}{container-type:inline-size;text-align:left}
${SCOPE} *,${SCOPE} *::before,${SCOPE} *::after{box-sizing:border-box}
${SCOPE} :where(h1,h2,h3,h4,p,ul,ol,figure,blockquote){padding:0;border:0;background:none;text-transform:none;font-style:normal}
${SCOPE} :where(h1,h2,h3,h4){font-family:var(--hea-font-sans)}
${SCOPE} :where(a){box-shadow:none;border:0}
${SCOPE} :where(button,input,select,textarea){font:inherit;letter-spacing:normal;text-transform:none;text-shadow:none;box-shadow:none;min-height:0}
${SCOPE} :where(button){margin:0;width:auto;height:auto}
${SCOPE} :where(table,thead,tbody,tr,th,td){border:0;background:none;margin:0}
${SCOPE} :where(table){width:100%;border-collapse:collapse}
${SCOPE} :where(code){font-family:ui-monospace,SFMono-Regular,Menlo,Consolas,monospace;background:none;padding:0}
${SCOPE} .hea-et-back{max-width:720px;margin:0 auto var(--hea-s-4);font-size:var(--hea-text-sm)}
${SCOPE} .hea-et-back a{color:var(--hea-purple);text-decoration:none}
`;

// ---- HTML -----------------------------------------------------------------------

const read = (p) => readFileSync(p, "utf8");

function courseRef(href) {
  // https://holisticemailacademy.com/courses/slug/?utm_campaign=x&utm_content=y -> /courses/slug/?ref=email-tools-x-y
  const u = new URL(href.replace(/&amp;/g, "&"));
  const tool = u.searchParams.get("utm_campaign");
  const content = u.searchParams.get("utm_content");
  if (!tool) return u.pathname;
  return `${u.pathname}?ref=email-tools-${tool}${content ? `-${content}` : ""}`;
}

export function rewriteLinks(html) {
  return html
    // Links between tools become placeholders the plugin fills in.
    .replace(/href="([a-z0-9-]+\.html)((?:[?#][^"]*)?)"/g, (m, file, rest) => {
      const key = FILE_TO_KEY[file];
      if (!key) throw new Error(`Link to unknown page ${file}`);
      return `href="{{page:${key}}}${rest}"`;
    })
    // Academy links stay on the site, in the same tab.
    .replace(/href="(https:\/\/holisticemailacademy\.com\/courses\/[^"]*)"/g, (m, url) => `href="${courseRef(url)}"`)
    .replace(/href="https:\/\/holisticemailacademy\.com(\/[^"]*)"/g, 'href="$1"')
    // Same-site links open in the same tab.
    .replace(/<a\b[^>]*>/g, (tag) =>
      /href="(\/|\{\{page:)/.test(tag) ? tag.replace(/\s+target="_blank"/, "").replace(/\s+rel="noopener"/, "") : tag);
}

function extractPage(file) {
  const html = read(join(PAGES, file));
  const main = html.match(/<main>([\s\S]*)<\/main>/)?.[1];
  if (!main) throw new Error(`${file}: no <main>`);
  const title = html.match(/<title>([^<]*)<\/title>/)[1].replace(/\s+—\s+Holistic Email Marketing$/, "").trim();
  const description = html.match(/<meta name="description" content="([^"]*)"/)?.[1] ?? "";
  const styles = [...html.matchAll(/<style>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join("\n");
  const modules = [...html.matchAll(/<script type="module"[^>]*src="\/email-tools\/assets\/([^"]+)"/g)].map((m) => m[1]);
  const sheets = [...html.matchAll(/<link rel="stylesheet"[^>]*href="(?:\/email-tools\/)?assets\/([^"]+)"/g)].map((m) => m[1]);
  const inline = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map((m) => m[1].trim());
  const ldjson = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)].map((m) => m[1].trim());
  return { main, title, description, styles, modules, sheets, inline, ldjson };
}

function toTemplate(key, main) {
  let body = main;
  // One H1 per page: the WordPress page title. The tool's own H1 goes; on the
  // index the hero headline becomes an H2.
  if (key === "index") body = body.replace(/<h1>([\s\S]*?)<\/h1>/, '<h2 class="h1">$1</h2>');
  else body = body.replace(/\s*<h1>[\s\S]*?<\/h1>/, "");
  if (/<h1[\s>]/.test(body)) throw new Error(`${key}: a second H1 is left`);
  return rewriteLinks(body).trim() + "\n";
}

// ---- Build ------------------------------------------------------------------------

export function build(out = OUT) {
  for (const d of ["templates", "assets/js", "assets/css", "assets/fonts"]) {
    rmSync(join(out, d), { recursive: true, force: true });
    mkdirSync(join(out, d), { recursive: true });
  }

  // Fonts: the woff2 files the maturity assessment already ships.
  for (const f of ["CMGSans-Regular.woff2", "CMGSans-SemiBold.woff2"]) copyFileSync(join(FONTS, f), join(out, "assets/fonts", f));

  // Shared CSS, scoped.
  const fontCss = (css) =>
    css.replace(/url\((['"]?)CMGSans-(Regular|SemiBold)\.ttf\1\)\s*format\((['"])truetype\3\)/g, 'url("../fonts/CMGSans-$2.woff2") format("woff2")');
  const sharedSheets = ["style.css", "tool-page.css", "course-cta.css"];
  const shared = sharedSheets.map((f) => scopeCss(fontCss(read(join(SRC, "assets", f))))).join("\n");
  const sharedOut = `/* ${GENERATED} */\n${RESET}\n${shared}`;
  writeFileSync(join(out, "assets/css/email-tools.css"), sharedOut);

  // Every script module, with versioned relative imports.
  const jsDir = join(SRC, "assets");
  const jsFiles = readdirSync(jsDir).filter((f) => f.endsWith(".js")).sort();
  // A file's version covers its own source and, through them, every file it
  // imports: change utils.js and every module that imports it gets a new URL.
  const IMPORT_RE = /(from\s+|import\s*\(\s*)(["'])\.\/([\w.-]+\.js)\2/g;
  const sources = Object.fromEntries(jsFiles.map((f) => [f, read(join(jsDir, f))]));
  const versions = {};
  const versionOf = (f, seen = new Set()) => {
    if (versions[f]) return versions[f];
    if (seen.has(f)) throw new Error(`Import cycle through ${f}`);
    seen.add(f);
    const deps = [...sources[f].matchAll(IMPORT_RE)].map((m) => m[3]);
    for (const d of deps) if (!sources[d]) throw new Error(`${f} imports ${d}, which isn't in email-tools/assets`);
    return (versions[f] = hash(sources[f] + deps.map((d) => versionOf(d, seen)).join()));
  };
  jsFiles.forEach((f) => versionOf(f));
  for (const f of jsFiles) {
    const code = sources[f].replace(IMPORT_RE, (m, pre, q, dep) => {
      if (!versions[dep]) throw new Error(`${f} imports ${dep}, which isn't in email-tools/assets`);
      return `${pre}${q}./${dep}?v=${versions[dep]}${q}`;
    });
    writeFileSync(join(out, "assets/js", f), `// ${GENERATED}\n${code}`);
  }

  const css = { "email-tools.css": hash(sharedOut) };
  // Every file's content hash: the PHP loads entry scripts at exactly the URL
  // other modules import them by (./x.js?v=hash), so no module runs twice.
  const manifest = { version: hash(JSON.stringify(versions) + sharedOut), scripts: versions, styles: css, tools: {} };
  for (const [key, file] of Object.entries(TOOL_FILES)) {
    const page = extractPage(file);
    writeFileSync(join(out, "templates", `${key}.html`), `<!-- ${GENERATED} -->\n${toTemplate(key, page.main)}`);

    const extraSheets = page.sheets.filter((s) => !sharedSheets.includes(s));
    let pageCss = page.styles ? scopeCss(page.styles) : "";
    for (const s of extraSheets) pageCss += scopeCss(read(join(SRC, "assets", s)));
    if (pageCss) {
      writeFileSync(join(out, "assets/css", `${key}.css`), `/* ${GENERATED} */\n${pageCss}`);
      manifest.styles[`${key}.css`] = hash(pageCss);
    }

    const classic = page.inline.length ? `${key}-inline.js` : null;
    if (classic) {
      const code = `// ${GENERATED}\n${page.inline.map((c) => `;${c}`).join("\n")}\n`;
      writeFileSync(join(out, "assets/js", classic), code);
      manifest.scripts[classic] = hash(code);
    }

    for (const m of page.modules) if (!versions[m]) throw new Error(`${file} loads ${m}, which isn't in email-tools/assets`);
    manifest.tools[key] = {
      title: page.title,
      description: page.description,
      modules: page.modules,
      css: pageCss ? `${key}.css` : null,
      classic,
      ldjson: page.ldjson,
    };
  }
  writeFileSync(join(out, "tools.json"), JSON.stringify(manifest, null, 2) + "\n");
  return manifest;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const m = build();
  console.log(`Built ${Object.keys(m.tools).length} pages into ${OUT} (version ${m.version})`);
}
